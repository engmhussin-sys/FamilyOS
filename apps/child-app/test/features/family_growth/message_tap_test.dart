// A TAP ON A MESSAGE CARD NOW LANDS SOMEWHERE — the in-app half of `abny://`.
//
// `test/core/routing/deep_link_test.dart` proves the parser and the map. This
// file proves the WIRING: that the card a child actually touches reaches
// `ChildDeepLinkRouter`, that the tab underneath changes, that a card with no
// link offers no tap at all, and that the entry point a future push handler
// will call goes through the same resolver rather than a second one.
//
// THE HARNESS MIRRORS PRODUCTION, and that is load-bearing here.
// `MyGrowthScreen` is PUSHED, under the same route name `ChildHomeShell` uses
// for its app-bar icon, because half of what this file asserts is about which
// route the child is standing on when they tap.
//
// WHAT IS DELIBERATELY NOT ASSERTED: that a real message carries a link.
// `/life-intelligence/self/messages` rows do not carry `deepLink` today — the
// field travels on the `notifications` table, whose read endpoints are
// parent-guarded — so the fixture below supplies one exactly as the server
// will when either that field or push delivery lands. Asserting anything else
// would be asserting a payload this app has never received.
//
// EXECUTION STATUS: NEVER RUN. There is no Flutter SDK and no Dart SDK in the
// authoring environment, and pub.dev is unreachable, so these tests have never
// been executed. They are STATIC VERIFIED by `scripts/dart_preflight.py`,
// `scripts/verify_dart_imports.py` and `scripts/verify_l10n_parity.py` only.

