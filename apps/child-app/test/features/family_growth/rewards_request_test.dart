import 'package:child_app/features/family_growth/presentation/rewards_screen.dart';

/// Hand-written rather than generated by `mockito`, for the reason every other
/// fake in this app gives: codegen needs `pub get`, and pub.dev is not
/// reachable from where these were written.
class _FakeGrowthApi implements FamilyGrowthApi {
  _FakeGrowthApi({required this.coins, required this.store});

  final int coins;
  final List<dynamic> store;

  /// The catalogue ids `redeemReward` was actually called with. A screen that
  /// silently drops the tap leaves this empty, which is the failure this file
  /// is written to catch.
  final List<String> requested = <String>[];

  @override
  Future<Map<String, dynamic>> getRewardsAccount() async =>
      <String, dynamic>{'coins': coins, 'xp': 40, 'level': 2};

  @override
  Future<List<dynamic>> getRewardsStore() async => store;

  @override
  Future<void> redeemReward(String catalogItemId) async {
    requested.add(catalogItemId);
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => throw StateError(
        '_FakeGrowthApi has no stub for ${invocation.memberName} — if the '
        'rewards screen now calls it, stub it here.',
      );
}

Map<String, dynamic> _item({
  String id = 'item_1',
  String title = 'رحلة الملاهي',
  int costCoins = 100,
}) =>
    <String, dynamic>{'id': id, 'title': title, 'costCoins': costCoins};

Future<void> _pumpRewards(WidgetTester tester, _FakeGrowthApi api) async {
  GoogleFonts.config.allowRuntimeFetching = false;

  await tester.pumpWidget(
    ProviderScope(
      overrides: [
        familyGrowthApiProvider.overrideWithValue(api),
        localeControllerProvider.overrideWith(
          (ref) => LocaleController(storage: InMemoryLocaleStorage(AppLocale.ar)),
        ),
      ],
      child: MaterialApp(
        debugShowCheckedModeBanner: false,
        locale: const Locale('ar'),
        localizationsDelegates: const [
          GlobalMaterialLocalizations.delegate,
          GlobalWidgetsLocalizations.delegate,
          GlobalCupertinoLocalizations.delegate,
        ],
        supportedLocales: const [Locale('ar'), Locale('en')],
        home: const RewardsScreen(),
      ),
    ),
  );

  // Not pumpAndSettle: the celebration overlay animates and would never
  // settle. One frame for the tree, one long one for the two awaited fetches.
  await tester.pump();
  await tester.pump(const Duration(seconds: 1));
}

String _ar(String key, {Map<String, Object>? options}) =>
    translate(AppLocale.ar, key, options: options);

void main() {
  group('a reward the child cannot yet afford', () {
    testWidgets('still reaches the server when tapped', (tester) async {
      final api = _FakeGrowthApi(
        coins: 90,
        store: [_item(costCoins: 100)],
      );
      await _pumpRewards(tester, api);

      await tester.tap(find.text(_ar('rewards.getIt')));
      await tester.pump();

      expect(api.requested, <String>['item_1']);
    });

    testWidgets('offers the SAME button as one the child can afford — no '
        '«need more» dead end', (tester) async {
      final api = _FakeGrowthApi(coins: 90, store: [_item(costCoins: 100)]);
      await _pumpRewards(tester, api);

      final button = tester.widget<FilledButton>(find.byType(FilledButton));
      expect(button.onPressed, isNotNull);
      expect(find.text(_ar('rewards.getIt')), findsOneWidget);
    });

    testWidgets('says how short the child is, and that asking is allowed',
        (tester) async {
      final api = _FakeGrowthApi(coins: 90, store: [_item(costCoins: 100)]);
      await _pumpRewards(tester, api);

      expect(
        find.text(_ar('rewards.askAnyway', options: {'count': 10})),
        findsOneWidget,
      );
    });

    testWidgets('says nothing about a shortfall when there is none',
        (tester) async {
      final api = _FakeGrowthApi(coins: 120, store: [_item(costCoins: 100)]);
      await _pumpRewards(tester, api);

      expect(
        find.text(_ar('rewards.askAnyway', options: {'count': 10})),
        findsNothing,
      );
      expect(find.text(_ar('rewards.getIt')), findsOneWidget);
    });
  });

  group('an empty family store', () {
    testWidgets('says so instead of showing a bare screen', (tester) async {
      final api = _FakeGrowthApi(coins: 10, store: const <dynamic>[]);
      await _pumpRewards(tester, api);

      expect(find.text(_ar('rewards.noRewardsYet')), findsOneWidget);
    });
  });
}
