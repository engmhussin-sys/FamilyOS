// THE CHILD MAY ASK FOR A REWARD THEY CANNOT YET AFFORD.
//
// The server is explicit about this. `RewardsEngineService.requestRedemption`
// carries the reason above the method: «Requesting is allowed even if the
// child is currently short on coins — a parent may grant bonus coins after
// seeing the request. The balance check that actually matters happens at
// approval time.» It refuses only an unknown or inactive catalogue item.
//
// This screen used to disagree with it. `coins >= costCoins` decided locally,
// the button went grey and `onRedeem` went null, so a child ten coins short
// tapped a dead control and the parent never learned the child wanted the
// thing — a request that the server would have accepted was stopped by the
// client that had no authority to stop it.
//
// These tests fail if the gate ever comes back: one taps a store item priced
// ABOVE the balance and asserts the call reaches the API.
//
// EXECUTION STATUS: NEVER RUN. There is no Flutter SDK and no Dart SDK in the
// authoring environment, and pub.dev is unreachable, so this file has never
// been executed. It is STATIC VERIFIED by `scripts/dart_preflight.py`,
// `scripts/verify_dart_imports.py` and `scripts/verify_l10n_parity.py` only.

